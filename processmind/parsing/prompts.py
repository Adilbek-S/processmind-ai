"""Промпты для извлечения процесса. Правила против выдумывания — общие для текста и изображения."""

_COMMON_RULES = """\
Ты извлекаешь бизнес-процесс из документа в структурированный вид. Отвечай на языке документа.

Жёсткие правила:
1. Извлекай ВСЕ операции процесса, ничего не пропускай и не объединяй разные операции в одну.
   Условия/проверки («Заявка корректна?») оформляй отдельной операцией с несколькими next_orders.
2. Не придумывай данные. Если значение не указано явно — верни null (для execution_type — "unknown").
3. actor заполняй только если исполнитель явно назван для этой операции (или операция стоит в его
   дорожке на схеме). Не выводи исполнителя из здравого смысла.
4. Длительность заполняй только если она явно указана в источнике. В duration_quote верни точную
   цитату оттуда; если цитаты нет — длительность должна быть null. Не оценивай и не округляй «на глаз».
5. execution_type: "manual" или "automated" ставь только если слово или явный синоним («вручную»,
   «автоматически», «системой») напечатано в тексте этой операции. Не выводи тип из названия или
   из смысла операции. Во всех остальных случаях — "unknown".
6. next_orders — реальные связи: для линейной последовательности это номер следующей операции;
   при ветвлении — номера всех веток; у завершающих операций — пустой список.
7. participants — только те участники, что названы в источнике.
8. Всё, что не удалось разобрать или прочитать, перечисли в uncertainties. Лучше честно указать
   неуверенность, чем угадать.
"""

