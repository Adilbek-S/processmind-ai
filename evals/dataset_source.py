"""Исходник Golden Dataset: 30 синтетических примеров (не реальные регламенты).

Запуск `python -m evals.build_dataset` записывает `evals/golden_dataset.json`. Все процессы, организации и
ситуации выдуманы; ID паттернов относятся к синтетической базе знаний из `knowledge_base/automation_patterns/`.

Смысл полей (см. также evals/dataset.py):
- `kind`: positive — есть ожидаемые паттерны; negative — автоматизация не обоснована, рекомендаций быть не должно;
  ambiguous — описание неоднозначно: обязательных рекомендаций нет, но недопустимые запрещены.
- `expected_pattern_ids` — паттерны, которые должны быть предложены (для Recommendation F1 и Hit@3).
- `acceptable_recommendations` — дополнительно допустимые (операция, паттерны): не поощряются и не штрафуются.
- `unacceptable_recommendations` — то, что предлагать нельзя (операция и/или паттерны, причина).
"""

from __future__ import annotations

from typing import Any


def S(step_id: str, name: str, actor: str | None, manual: bool | None, minutes: float | None, *, desc: str | None = None, pain: list[str] | None = None) -> dict:
    step: dict[str, Any] = {"id": step_id, "name": name, "actor": actor, "is_manual": manual, "duration_minutes": minutes}
    if desc:
        step["description"] = desc
    if pain:
        step["pain_points"] = pain
    return step


def P(process_id: str, name: str, *steps: dict) -> dict:
    """Процесс с последовательными связями между операциями."""
    for a, b in zip(steps, steps[1:]):
        a["next_steps"] = [b["id"]]
    return {"process_id": process_id, "name": name, "steps": list(steps)}


def OK(step_id: str, *patterns: str) -> dict:
    return {"step_id": step_id, "pattern_ids": list(patterns)}


def NO(step_id: str, reason: str, *patterns: str) -> dict:
    """Недопустимая рекомендация: для операции (и, если указаны паттерны, только с этими паттернами)."""
    return {"step_id": step_id, "pattern_ids": list(patterns) or None, "reason": reason}


def case(test_id: str, category: str, kind: str, description: str, process: dict, question: str, target: str | None, expected: list[str], acceptable: list[dict], unacceptable: list[dict]) -> dict:
    return {
        "test_id": test_id,
        "category": category,
        "kind": kind,
        "description": description,
        "process": process,
        "question": question,
        "target_step_id": target,
        "expected_pattern_ids": expected,
        "acceptable_recommendations": acceptable,
        "unacceptable_recommendations": unacceptable,
    }


